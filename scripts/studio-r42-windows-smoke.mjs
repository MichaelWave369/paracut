import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

const read = relative => readFileSync(new URL('../'+relative, import.meta.url),'utf8');
const launcher = read('ParaCut Export MP4.cmd');
const ps = read('tools/windows-export.ps1');
const html = read('apps/desktop/public/studio.html');
const workflow = read('.github/workflows/ci.yml');
const guide = read('docs/STUDIO_R42.md');

assert.match(launcher, /powershell\.exe -NoLogo -NoProfile -STA -ExecutionPolicy Bypass -File "%~dp0tools\\windows-export\.ps1"/);
assert.match(launcher, /set "PARACUT_EXIT=%ERRORLEVEL%"/);
assert.match(launcher, /\bpause\b/);
assert.match(ps, /Add-Type -AssemblyName System\.Windows\.Forms/);
assert.match(ps, /OpenFileDialog/);
assert.match(ps, /FolderBrowserDialog/);
assert.match(ps, /SaveFileDialog/);
assert.match(ps, /Get-Command node\.exe/);
assert.match(ps, /Get-Command ffmpeg\.exe/);
assert.match(ps, /Get-Command ffprobe\.exe/);
assert.match(ps, /Join-Path \(Split-Path -Parent \$selected\) 'ffprobe\.exe'/);
assert.match(ps, /Test-Path -LiteralPath \$output/);
assert.match(ps, /Output already exists\. ParaCut never overwrites/);
assert.match(ps, /--dry-run/);
assert.match(ps, /if \(\$LASTEXITCODE -ne 0\)/);
assert.match(ps, /ParaCut: confirm MP4 render/);
assert.match(ps, /if \(\$confirm -ne \[System\.Windows\.Forms\.DialogResult\]::Yes\)/);
assert.match(ps, /Verified local MP4 export completed/);
assert.match(ps, /& \$node\.Source \$renderer --draft \$draft --media-dir \$mediaDir --out \$output --ffmpeg \$ffmpegPath --ffprobe \$ffprobePath/);
const dry=ps.indexOf(' --dry-run'),prompt=ps.indexOf('ParaCut: confirm MP4 render');
const render=ps.lastIndexOf('    & $node.Source $renderer --draft');
assert.ok(dry > 0 && prompt > dry && render > prompt, 'validate and confirm before render');
assert.doesNotMatch(ps,/^\s*(Invoke-Expression|iex|Set-ExecutionPolicy|Start-Process|Invoke-WebRequest)\s/mi);
assert.match(workflow,/windows-launcher-parse:/);
assert.match(workflow,/runs-on: windows-latest/);
assert.match(workflow,/Language\.Parser]::ParseFile/);
assert.match(html,/Local multitrack MP4 guide/);
assert.match(html,/docs\/STUDIO_R56\.md/);
assert.match(guide,/not a feature the GitHub Pages website can run by itself/);
console.log('ParaCut R4.2 Windows launch smoke PASS: double-click flow, local-only execution, safe argument boundaries, dry-run before confirmation, no-overwrite and Windows parser CI.');
